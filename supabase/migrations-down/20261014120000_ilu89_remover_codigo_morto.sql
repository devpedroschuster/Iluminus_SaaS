-- 7. Funções (texto de pg_get_functiondef em produção)
CREATE OR REPLACE FUNCTION public.realizar_agendamento(id_aula_input integer, id_aluno_input integer)
 RETURNS text
 LANGUAGE plpgsql
AS $function$
DECLARE
    vagas_ocupadas INT;
    vagas_totais INT;
BEGIN
    -- 1. Busca a capacidade da aula específica
    SELECT capacidade INTO vagas_totais 
    FROM public.agendas 
    WHERE id = id_aula_input;

    -- 2. Se a capacidade for nula, tentamos buscar um valor padrão ou retornar erro detalhado
    IF vagas_totais IS NULL THEN
        RETURN 'Erro: A aula ID ' || id_aula_input || ' está com a coluna capacidade vazia (NULL) no banco.';
    END IF;

    -- 3. Conta as inscrições
    SELECT count(*)::int INTO vagas_ocupadas 
    FROM public.inscricoes 
    WHERE agenda_id = id_aula_input;

    -- 4. Lógica de reserva
    IF vagas_ocupadas < vagas_totais THEN
        -- Verifica duplicata
        IF EXISTS (SELECT 1 FROM public.inscricoes WHERE agenda_id = id_aula_input AND aluno_id = id_aluno_input) THEN
            RETURN 'Você já reservou esta aula!';
        END IF;

        INSERT INTO public.inscricoes (agenda_id, aluno_id) VALUES (id_aula_input, id_aluno_input);
        RETURN 'Sucesso! Reserva confirmada.';
    ELSE
        RETURN 'Erro: Esta aula atingiu o limite de ' || vagas_totais || ' vagas.';
    END IF;
END;
$function$;
ALTER FUNCTION public.realizar_agendamento(integer, integer) OWNER TO postgres;
GRANT EXECUTE ON FUNCTION public.realizar_agendamento(integer, integer) TO PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.matricular_aluno(p_aluno_id bigint, p_plano_id integer, p_data_inicio date, p_data_fim date, p_vencimento date, p_modalidades text[], p_valor_pago numeric, p_descricao text, p_forma_recebimento text DEFAULT 'recorrente'::text)
 RETURNS void
 LANGUAGE plpgsql
AS $function$
DECLARE
  v_tipo_aula text;
  v_preco numeric;
  v_duracao_meses integer;
  v_valor_integral numeric;
BEGIN
  SELECT CASE WHEN is_plano_livre THEN 'plano_livre' ELSE 'regular' END,
         preco, duracao_meses
    INTO v_tipo_aula, v_preco, v_duracao_meses
    FROM planos
   WHERE id = p_plano_id;

  UPDATE alunos
     SET plano_id                 = p_plano_id,
         modalidades_selecionadas = p_modalidades,
         ativo                    = true,
         data_inicio_plano        = p_data_inicio,
         data_fim_plano           = p_data_fim
   WHERE id = p_aluno_id;

  UPDATE historico_planos
     SET status = 'finalizado'
   WHERE aluno_id = p_aluno_id
     AND status   = 'ativo';

  INSERT INTO historico_planos (aluno_id, plano_id, data_inicio, data_fim, status, valor_pago, forma_recebimento)
  VALUES (p_aluno_id, p_plano_id, p_data_inicio, p_data_fim, 'ativo', p_valor_pago, p_forma_recebimento);

  -- 'a_vista': uma única mensalidade cobrindo o ciclo inteiro (preço
  -- mensal × duração, congelado em valor_esperado). 'recorrente': mantém o
  -- comportamento histórico de uma mensalidade no valor mensal do plano; as
  -- demais são criadas mês a mês (cron gerar-mensalidades / financeiroService
  -- .gerarMensalidades, que pulam vencimentos cobertos por ciclo à vista).
  IF p_forma_recebimento = 'a_vista' THEN
    DELETE FROM mensalidades
     WHERE aluno_id = p_aluno_id
       AND status IN ('pendente', 'atrasado')
       AND tipo_aula IN ('regular', 'plano_livre')
       AND data_vencimento BETWEEN p_data_inicio AND p_data_fim;

    v_valor_integral := v_preco * COALESCE(v_duracao_meses, 1);
    INSERT INTO mensalidades (aluno_id, plano_id, data_vencimento, status, descricao, tipo_aula, valor_esperado)
    VALUES (p_aluno_id, p_plano_id, p_vencimento, 'pendente', COALESCE(p_descricao || ' — ', '') || 'Pagamento integral do plano', v_tipo_aula, v_valor_integral);
  ELSE
    INSERT INTO mensalidades (aluno_id, plano_id, data_vencimento, status, descricao, tipo_aula)
    VALUES (p_aluno_id, p_plano_id, p_vencimento, 'pendente', p_descricao, v_tipo_aula);
  END IF;
END;
$function$;
ALTER FUNCTION public.matricular_aluno(bigint, integer, date, date, date, text[], numeric, text, text) OWNER TO postgres;
GRANT EXECUTE ON FUNCTION public.matricular_aluno(bigint, integer, date, date, date, text[], numeric, text, text) TO PUBLIC, anon, authenticated, service_role;
